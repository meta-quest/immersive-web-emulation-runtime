function interfaceShape(idl, name) {
  const f = flatten(idl, name);
  const consts = f.consts.map((c) => [c.name, c.value]);
  const byName = new Map();
  for (const op of f.ops) {
    if (!byName.has(op.name)) byName.set(op.name, []);
    byName.get(op.name).push(op);
  }
  const ops = [...byName].map(([n, list]) => [n, overloadLength(list)]);
  const attrs = f.attrs.filter(shipped).map((a) => [a.name, a.readonly]);
  return { consts, ops, attrs };
}

// Members Chromium marks RuntimeEnabled are excluded from the surface unless the feature ships in Quest
// Browser (WebXR: makeXRCompatible).
const SHIPPED_FEATURES = new Set(['RuntimeEnabled=WebXR']);
function shipped(member) {
  return !member.ext.some(
    (e) => e.startsWith('RuntimeEnabled') && !SHIPPED_FEATURES.has(e),
  );
}
function shippedOps(idl, name) {
  return flatten(idl, name).ops.filter(shipped);
}

