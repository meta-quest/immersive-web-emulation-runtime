/**
 * Coverage check (binding-table.mjs header): every shipped IDL operation of the WebGL 1 / WebGL 2 contexts and
 * of each offered extension interface is either `direct` (generated here) or has a hand-written method in
 * web/webgl/*.ts (a `name(this: ...)` definition). Fails the generator otherwise. Returns the counts.
 */
export function checkCoverage(inputs) {
  const { idl } = inputs;
  const sources = readdirSync(webDir)
    .filter((f) => f.endsWith('.ts'))
    .map((f) => readFileSync(join(webDir, f), 'utf8'))
    .join('\n');
  const handWritten = new Set();
  for (const m of sources.matchAll(/^\s+(\w+)\s*\(\s*this\s*:/gm))
    handWritten.add(m[1]);
  const direct = new Set(
    Object.keys(table.DIRECT).filter((k) => !table.DIRECT[k].custom),
  );
  const missing = [];
  let generated = 0;
  let custom = 0;
  const check = (iface, key, name) => {
    if (direct.has(key)) generated++;
    else if (handWritten.has(name)) custom++;
    else missing.push(`${iface}.${name}`);
  };
  const seen = new Set();
  for (const iface of ['WebGLRenderingContext', 'WebGL2RenderingContext']) {
    for (const op of shippedOps(idl, iface)) {
      if (seen.has(op.name)) continue;
      seen.add(op.name);
      check(iface, op.name, op.name);
    }
  }
  const ifaces = new Set(
    [
      ...Object.values(table.EXTENSIONS),
      ...Object.values(table.EXTENSIONS_WEBGL1),
    ]
      .map((e) => e[0])
      .filter(Boolean),
  );
  for (const iface of ifaces) {
    for (const op of shippedOps(idl, iface))
      check(iface, `${iface}.${op.name}`, op.name);
  }
  if (missing.length)
    throw new Error(
      `coverage: IDL operations neither generated nor hand-written: ${missing.join(', ')}`,
    );
  return { generated, custom };
}

export function generate(inputs = loadInputs()) {
  const natives = buildNatives(inputs);
  const coverage = checkCoverage(inputs);
  return {
    coverage,
    natives,
    files: {
      [join(glDir, 'generated', 'gl_api.gen.h')]: genApiHeader(inputs),
      [join(glDir, 'generated', 'gl_api.gen.cc')]: genApiSource(inputs),
      [join(glDir, 'generated', 'gl_natives.gen.cc')]: genNativesSource(
        inputs,
        natives,
      ),
      [join(glDir, 'generated', 'gl_composites.gen.h')]:
        genCompositeHeaderFragment(natives),
      [join(webDir, 'gen', 'natives.gen.ts')]: genNativesTs(natives),
      [join(webDir, 'gen', 'idl.gen.ts')]: genIdlTs(inputs.idl),
      [join(webDir, 'gen', 'methods.gen.ts')]: genMethodsTs(inputs, natives),
      [join(webDir, 'gen', 'enums.gen.ts')]: genEnumsTs(inputs.idl),
    },
  };
}

function main() {
  const check = process.argv.includes('--check');
  const { files, natives, coverage } = generate();
  let stale = 0;
  for (const [path, text] of Object.entries(files)) {
    const old = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (old === text) continue;
    stale++;
    if (check) {
      process.stderr.write(`stale: ${relative(pkgDir, path)}\n`);
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, text);
      process.stdout.write(`wrote ${relative(pkgDir, path)}\n`);
    }
  }
  const fast = natives.filter((n) => n.fast).length;
  process.stdout.write(
    `${natives.length} natives (${fast} with a fast-API path)\n`,
  );
  process.stdout.write(
    `IDL coverage: ${coverage.generated} generated WebGL methods, ${coverage.custom} hand-written\n`,
  );
  if (check && stale) process.exit(1);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
