// WebGL 2 binding generator (spec GL-PERF-1). Reads:
//   - the NDK GLES 3.2 headers (GLES3/gl32.h, GLES2/gl2ext.h): C signatures + enum values,
//   - the WebGL IDL (gen/idl/*.idl, Chromium revision in gen/idl/REVISION) + EXTRA_IDL from the binding table,
//   - gen/binding-table.mjs: the documented special cases.
// Writes (all checked in, regenerate with `node runtime/gl/gen/generate.mjs`; `--check` fails if stale):
//   runtime/gl/generated/gl_api.gen.h / gl_api.gen.cc       GLES function table + loader
//   runtime/gl/generated/gl_natives.gen.cc                  V8 natives: fast-API CFunction + slow callback each
//   web/webgl/gen/natives.gen.ts                            TS declaration of the natives object
//   web/webgl/gen/idl.gen.ts                                IDL shape: constants, operations (+ length), attributes
//   web/webgl/gen/methods.gen.ts                            generated `direct` WebGL methods
//
// Environment: IWN_NDK_SYSROOT overrides the header location (default: the sysroot of $ANDROID_NDK_HOME's toolchain).

