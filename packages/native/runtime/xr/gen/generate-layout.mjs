#!/usr/bin/env node
// Generates the frame record offsets for both sides of the native/JS boundary from layout/frame-record.json (XRF-4):
//   runtime/xr/include/iwn/xr/frame_record_layout.gen.h   C++ byte offsets (the XR thread writes the record)
//   web/xr/src/layout.gen.ts                              typed-array element indices (the adapter reads it)
//
//   node runtime/xr/gen/generate-layout.mjs           write both files
//   node runtime/xr/gen/generate-layout.mjs --check   exit 1 if either checked-in file is stale
//
// Order of the record: the non-hand 4-byte fields in declaration order (so layoutVersion is the first word), padding
// to 8, the f64 fields, then one contiguous block per hand (left, then right: its 4-byte fields, then its u8 fields,
// padded to 4), then non-hand u8 fields; the total is rounded up to `align`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const xrDir = path.resolve(here, '..');
const pkgDir = path.resolve(xrDir, '../..');
const layoutPath = path.join(xrDir, 'layout/frame-record.json');
const cppOut = path.join(xrDir, 'include/iwn/xr/frame_record_layout.gen.h');
const tsOut = path.join(pkgDir, 'web/xr/src/layout.gen.ts');

const SIZE = { u8: 1, u32: 4, f32: 4, f64: 8 };
const HANDS = ['left', 'right'];

export function computeLayout(spec) {
  if (!Number.isInteger(spec.version) || spec.version < 1) throw new Error('layout: version must be a positive integer');
  const seen = new Set();
  for (const f of spec.fields) {
    if (!SIZE[f.type]) throw new Error(`layout: field ${f.name} has unknown type ${f.type}`);
    if (seen.has(f.name)) throw new Error(`layout: duplicate field ${f.name}`);
    seen.add(f.name);
    if (f.count !== undefined && (!Number.isInteger(f.count) || f.count < 1)) throw new Error(`layout: bad count for ${f.name}`);
  }
  if (spec.fields[0]?.name !== 'layoutVersion' || spec.fields[0].type !== 'u32') {
    throw new Error('layout: the first field must be the u32 layoutVersion (XRF-4)');
  }
  const out = []; // { name, type, count, perHand, hand, offset, doc }
  let at = 0;
  const place = (f, hand) => {
    const size = SIZE[f.type];
    if (at % size !== 0) throw new Error(`layout: misaligned ${f.name}`);
    out.push({ name: f.name, type: f.type, count: f.count ?? 1, perHand: !!f.perHand, hand, offset: at, doc: f.doc ?? '' });
    at += size * (f.count ?? 1);
  };
  const four = (f) => SIZE[f.type] === 4;
  for (const f of spec.fields) if (!f.perHand && four(f)) place(f);
  at = Math.ceil(at / 8) * 8;
  for (const f of spec.fields) if (!f.perHand && f.type === 'f64') place(f);
  for (const hand of HANDS) {
    for (const f of spec.fields) if (f.perHand && f.type === 'f64') throw new Error(`layout: per-hand f64 (${f.name}) is not supported`);
    for (const f of spec.fields) if (f.perHand && four(f)) place(f, hand);
    for (const f of spec.fields) if (f.perHand && f.type === 'u8') place(f, hand);
    at = Math.ceil(at / 4) * 4;
  }
  for (const f of spec.fields) if (!f.perHand && f.type === 'u8') place(f);
  const align = spec.align ?? 64;
  const bytes = Math.ceil(at / align) * align;
  return { version: spec.version, bytes, align, fields: out };
}

const pascal = (s) => s[0].toUpperCase() + s.slice(1);

export function renderCpp(layout) {
  const lines = [
    '// Generated by runtime/xr/gen/generate-layout.mjs from runtime/xr/layout/frame-record.json. Do not edit.',
    '// Byte offsets of the XR frame record (docs/spec/09, XRF-1..7). Per-hand fields: [0] left, [1] right.',
    '#pragma once',
    '',
    '#include <cstddef>',
    '#include <cstdint>',
    '',
    'namespace iwn::xr::layout {',
    '',
    `inline constexpr uint32_t kVersion = ${layout.version};`,
    `inline constexpr size_t kBytes = ${layout.bytes};`,
    `inline constexpr size_t kAlign = ${layout.align};`,
    '',
  ];
  const done = new Set();
  for (const f of layout.fields) {
    if (done.has(f.name)) continue;
    done.add(f.name);
    const doc = f.doc ? `  // ${f.type}${f.count > 1 ? `[${f.count}]` : ''}: ${f.doc}` : `  // ${f.type}${f.count > 1 ? `[${f.count}]` : ''}`;
    if (f.perHand) {
      const l = layout.fields.find((g) => g.name === f.name && g.hand === 'left');
      const r = layout.fields.find((g) => g.name === f.name && g.hand === 'right');
      lines.push(`inline constexpr size_t k${pascal(f.name)}[2] = {${l.offset}, ${r.offset}};${doc}`);
    } else {
      lines.push(`inline constexpr size_t k${pascal(f.name)} = ${f.offset};${doc}`);
    }
    if (f.count > 1) lines.push(`inline constexpr size_t k${pascal(f.name)}Count = ${f.count};`);
  }
  lines.push('', '}  // namespace iwn::xr::layout', '');
  return lines.join('\n');
}

export function renderTs(layout) {
  const groups = { F64: {}, U32: {}, F32: {}, U8: {} };
  const hand = { U32: {}, F32: {}, U8: {} };
  const counts = {};
  for (const f of layout.fields) {
    const key = f.type.toUpperCase();
    const index = f.offset / { u8: 1, u32: 4, f32: 4, f64: 8 }[f.type];
    if (f.perHand) {
      (hand[key][f.name] ??= [0, 0])[f.hand === 'left' ? 0 : 1] = index;
    } else {
      groups[key][f.name] = index;
    }
    if (f.count > 1) counts[f.name] = f.count;
  }
  const obj = (o) =>
    Object.keys(o).length === 0
      ? '{} as const'
      : `{\n${Object.entries(o)
          .map(([k, v]) => `  ${k}: ${Array.isArray(v) ? `[${v.join(', ')}] as const` : v},`)
          .join('\n')}\n} as const`;
  return [
    '// Generated by runtime/xr/gen/generate-layout.mjs from runtime/xr/layout/frame-record.json. Do not edit.',
    '// Element indices into typed-array views over the native XR frame record (docs/spec/09, XRF-4).',
    '// Per-hand entries: [left, right].',
    '',
    `export const LAYOUT_VERSION = ${layout.version};`,
    `export const RECORD_BYTES = ${layout.bytes};`,
    '',
    '/** Indices into a Float64Array over the record. */',
    `export const F64 = ${obj(groups.F64)};`,
    '/** Indices into a Uint32Array over the record. */',
    `export const U32 = ${obj(groups.U32)};`,
    '/** Indices into a Float32Array over the record. */',
    `export const F32 = ${obj(groups.F32)};`,
    '/** Indices into a Uint8Array over the record. */',
    `export const U8 = ${obj(groups.U8)};`,
    '/** Per-hand indices ([left, right]) into a Uint32Array over the record. */',
    `export const HAND_U32 = ${obj(hand.U32)};`,
    '/** Per-hand indices ([left, right]) into a Float32Array over the record. */',
    `export const HAND_F32 = ${obj(hand.F32)};`,
    '/** Per-hand indices ([left, right]) into a Uint8Array over the record. */',
    `export const HAND_U8 = ${obj(hand.U8)};`,
    '/** Element counts of the array fields. */',
    `export const COUNTS = ${obj(counts)};`,
    '',
  ].join('\n');
}

function main() {
  const spec = JSON.parse(fs.readFileSync(layoutPath, 'utf8'));
  const layout = computeLayout(spec);
  const outputs = [
    [cppOut, renderCpp(layout)],
    [tsOut, renderTs(layout)],
  ];
  if (process.argv.includes('--check')) {
    let stale = 0;
    for (const [file, text] of outputs) {
      const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
      if (current !== text) {
        console.error(`stale: ${path.relative(pkgDir, file)} (run node runtime/xr/gen/generate-layout.mjs)`);
        stale++;
      }
    }
    process.exit(stale ? 1 : 0);
  }
  for (const [file, text] of outputs) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`wrote ${path.relative(pkgDir, file)}`);
  }
  console.log(`frame record v${layout.version}: ${layout.bytes} bytes`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main();
