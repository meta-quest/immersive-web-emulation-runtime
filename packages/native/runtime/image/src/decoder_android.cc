// Android AImageDecoder backend (NDK <android/imagedecoder.h>, API 30+). The functions are resolved from
// libjnigraphics.so at run time so the runtime still loads on API 29 (the template's minSdk); there the software
// backends take over. AImageDecoder decodes whatever the OS supports: PNG, JPEG, GIF, WebP, BMP, ICO, WBMP, HEIF
// and some AVIF. Measured on Horizon OS (2026-10-20): HEIF decodes; a plain 8-bit 4:2:0 AVIF decodes,
// other AVIFs (e.g. sRGB colour boxes, alpha + irot) fail inside AImageDecoder_decodeImage. IMG-1 does not ask for
// AVIF; DecodeOptions::allow_os_formats decides whether these formats are attempted at all.
#include "iwn/image/decode.h"

#if defined(__ANDROID__)
#include <android/bitmap.h>
#include <android/imagedecoder.h>
#include <android/log.h>
#include <dlfcn.h>

#include <mutex>
#include <utility>
#endif

