// Generates src/android_probes.inc: 2x1 images (red, blue) with EXIF orientation 6 as JPEG (APP1), PNG (eXIf)
// and WebP (EXIF chunk). The Android backend decodes their headers once to learn, per format, whether AImageDecoder
// applies EXIF orientation itself (reports 1x2) or not (2x1). On Quest (Android 14) it does for JPEG and WebP and
// does not for PNG.
// Usage: iwn_image_gen_probes > src/android_probes.inc
#include <cstdio>

#include "iwn/image/decode.h"
#include "test_images.h"

using namespace iwn::image::test;

namespace {
void Emit(const char* name, const Bytes& b) {
  std::printf("static const unsigned char %s[%zu] = {", name, b.size());
  for (size_t i = 0; i < b.size(); ++i) std::printf("%s0x%02x,", i % 16 ? " " : "\n    ", b[i]);
  std::printf("\n};\n");
}
}  // namespace

int main() {
  using iwn::image::Format;
  using iwn::image::ReadExifOrientation;
  Img img{2, 1, {255, 0, 0, 255, 0, 0, 255, 255}};
  Bytes jpg = InsertJpegExif(EncodeJpeg(img, 95), 6, false);
  Bytes png = InsertPngExif(EncodePng(img, 2, 8, false), 6);
  Bytes webp = InsertWebpExif(EncodeWebp(img, true, 100), 2, 1, 6, false);
  if (ReadExifOrientation(jpg.data(), jpg.size(), Format::kJpeg) != 6 ||
      ReadExifOrientation(png.data(), png.size(), Format::kPng) != 6 ||
      ReadExifOrientation(webp.data(), webp.size(), Format::kWebp) != 6) {
    return 1;
  }
  std::printf("// Generated by tools/gen_probes.cc. Do not edit.\n");
  Emit("kProbeJpeg", jpg);
  Emit("kProbePng", png);
  Emit("kProbeWebp", webp);
  return 0;
}
