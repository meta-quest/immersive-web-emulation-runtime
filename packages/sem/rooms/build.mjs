// Builds SEM's built-in GLTS rooms from rooms/src into rooms/<id>.js, ES
// modules whose default export is the room's GLTS source. SEM imports them
// lazily, so bundlers split each room into its own chunk and only load the
// one picked.
//
// rooms/src/<id>.ts are kit-based rooms: rooms/src/kit.ts is concatenated in
// front of them (GLTS scripts can only import 'three', '@drawcall/glts' and
// CDN packages, not local files). rooms/src/<id>.glts are standalone rooms.
//
//   node rooms/build.mjs            build every room
//   node rooms/build.mjs --check    also typecheck them
import { execFileSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, 'src');
const check = process.argv.includes('--check');
const require = createRequire(join(here, '..', 'package.json'));

// Rooms that were renamed or removed must not ship.
for (const file of readdirSync(here)) {
  if (file.endsWith('.js')) rmSync(join(here, file));
}

const kit = readFileSync(join(src, 'kit.ts'), 'utf8');
const header = (from) =>
  `// Generated by @iwer/sem rooms/build.mjs from ${from}; edit those and rebuild.`;
const built = [];
for (const file of readdirSync(src).sort()) {
  let id;
  let source;
  if (file.endsWith('.glts')) {
    id = file.slice(0, -5);
    source = readFileSync(join(src, file), 'utf8');
  } else if (file.endsWith('.ts') && file !== 'kit.ts') {
    id = file.slice(0, -3);
    const room = readFileSync(join(src, file), 'utf8');
    source = [
      header(`rooms/src/kit.ts and rooms/src/${file}`),
      "import * as THREE from 'three';",
      "import { onDispose, onFrame, scene } from '@drawcall/glts';",
      '',
      kit.trimEnd(),
      '',
      '// ' + '-'.repeat(70) + ' room',
      '',
      room.trimEnd(),
      '',
    ].join('\n');
  } else {
    continue;
  }
  writeFileSync(
    join(here, `${id}.js`),
    `${header(`rooms/src/${file}`)}\nexport default ${JSON.stringify(source)};\n`,
  );
  built.push({ id, source });
}
console.log(
  `built ${built.length} rooms: ${built.map(({ id }) => id).join(', ')}`,
);

if (check) {
  // Typecheck each room as a TypeScript module against the three and GLTS
  // types that SEM resolves.
  // Node's lookup of a package folder, which works for packages with an
  // exports map (GLTS) and for types-only packages alike.
  const packageDir = (name) => {
    for (const base of require.resolve.paths(name) ?? []) {
      if (existsSync(join(base, name, 'package.json'))) return join(base, name);
    }
    throw new Error(`Cannot find ${name} from @iwer/sem`);
  };
  const threeTypes = packageDir('@types/three');
  const glts = packageDir('@drawcall/glts');
  const dir = join(here, '.typecheck');
  mkdirSync(dir, { recursive: true });
  for (const { id, source } of built) {
    writeFileSync(join(dir, `${id}.ts`), source);
  }
  writeFileSync(
    join(dir, 'tsconfig.json'),
    JSON.stringify(
      {
        compilerOptions: {
          target: 'es2022',
          module: 'esnext',
          moduleResolution: 'bundler',
          lib: ['es2022', 'dom'],
          strict: true,
          noEmit: true,
          skipLibCheck: true,
          types: [],
          paths: {
            three: [join(threeTypes, 'index.d.ts')],
            'three/*': [join(threeTypes, '*')],
            '@drawcall/glts': [join(glts, 'dist', 'index.d.ts')],
          },
        },
        files: built.map(({ id }) => `${id}.ts`),
      },
      null,
      2,
    ),
  );
  const tsc = require.resolve('typescript/bin/tsc');
  try {
    execFileSync(process.execPath, [tsc, '-p', join(dir, 'tsconfig.json')], {
      stdio: 'inherit',
    });
    console.log('typecheck passed');
  } catch {
    process.exitCode = 1;
  }
}
